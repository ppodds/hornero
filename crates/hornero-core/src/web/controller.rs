/// A group of routes backed by an injectable struct.
///
/// The controller is constructed by the container like any provider; handlers receive `&self`
/// plus ordinary axum extractors. Written with `#[controller]` + `#[routes]`, or by hand:
///
/// ```ignore
/// impl Controller for TodoController {
///     fn routes(c: &mut ControllerDef<Self>) {
///         c.prefix("/todos").guard::<AuthGuard>();
///         c.get("/{id}", "find_one", |this: Arc<Self>, Path(id): Path<i64>| async move {
///             this.find_one(id).await
///         });
///     }
/// }
/// ```
#[diagnostic::on_unimplemented(
    message = "`{Self}` is not a controller",
    note = "add `#[routes]` to an impl block of `{Self}` (with `#[controller]` on the struct), or implement `hornero::Controller` by hand"
)]
pub trait Controller: Injectable {
    /// Registers the controller's routes, prefix and enhancers.
    fn routes(c: &mut ControllerDef<Self>);
}

/// Controller-level attributes generated by `#[controller(...)]` and consumed by `#[routes]`.
#[diagnostic::on_unimplemented(
    message = "`{Self}` is missing its controller attributes",
    note = "add `#[controller(\"/path\")]` to the struct definition"
)]
pub trait ControllerAttrs: Sized {
    /// Applies the prefix, enhancers and metadata from `#[controller(...)]`.
    fn configure(c: &mut ControllerDef<Self>);
}

/// Builder passed to [`Controller::routes`].
pub struct ControllerDef<C> {
    prefix: String,
    guards: Vec<EnhancerRef>,
    interceptors: Vec<EnhancerRef>,
    filters: Vec<EnhancerRef>,
    meta: Metadata,
    routes: Vec<RouteDef>,
    _controller: PhantomData<fn() -> C>,
}

/// One route registered on a controller. Handler-level enhancers and metadata go here.
pub struct RouteDef {
    pub(crate) method: Method,
    pub(crate) path: String,
    pub(crate) name: &'static str,
    pub(crate) guards: Vec<EnhancerRef>,
    pub(crate) interceptors: Vec<EnhancerRef>,
    pub(crate) filters: Vec<EnhancerRef>,
    pub(crate) meta: Metadata,
    /// `false` for methods axum's router cannot match; reported by the bootstrap.
    pub(crate) method_supported: bool,
    pub(crate) build: Box<dyn FnOnce(ErasedHandle) -> MethodRouter + Send>,
}

pub(crate) struct ControllerEntry {
    pub(crate) name: String,
    pub(crate) def: ProviderDef,
    pub(crate) prefix: String,
    pub(crate) guards: Vec<EnhancerRef>,
    pub(crate) interceptors: Vec<EnhancerRef>,
    pub(crate) filters: Vec<EnhancerRef>,
    pub(crate) meta: Metadata,
    pub(crate) routes: Vec<RouteDef>,
}

impl ControllerEntry {
    pub(crate) fn enhancers(&self) -> impl Iterator<Item = &EnhancerRef> {
        self.guards
            .iter()
            .chain(&self.interceptors)
            .chain(&self.filters)
            .chain(self.routes.iter().flat_map(|route| {
                route
                    .guards
                    .iter()
                    .chain(&route.interceptors)
                    .chain(&route.filters)
            }))
    }
}

impl<C: Controller> ControllerDef<C> {
    pub(crate) fn into_entry(self) -> ControllerEntry {
        ControllerEntry {
            name: short_type_name(type_name::<C>()),
            def: ProviderDef::injectable::<C>(),
            prefix: self.prefix,
            guards: self.guards,
            interceptors: self.interceptors,
            filters: self.filters,
            meta: self.meta,
            routes: self.routes,
        }
    }
}

// No `Controller` bound here, so a missing `#[routes]` is reported once, where the controller
// is registered, instead of on every builder call.
impl<C: Send + Sync + 'static> ControllerDef<C> {
    pub(crate) fn new() -> Self {
        Self {
            prefix: String::new(),
            guards: Vec::new(),
            interceptors: Vec::new(),
            filters: Vec::new(),
            meta: Metadata::default(),
            routes: Vec::new(),
            _controller: PhantomData,
        }
    }

    /// Path prefix shared by every route of this controller.
    pub fn prefix(&mut self, prefix: impl Into<String>) -> &mut Self {
        self.prefix = prefix.into();
        self
    }

    /// A guard for every route of this controller, run after global guards.
    pub fn guard<G: Guard + Injectable>(&mut self) -> &mut Self {
        self.guards.push(EnhancerRef::guard::<G>());
        self
    }

    /// An interceptor around every route of this controller, inside global interceptors.
    pub fn interceptor<I: Interceptor + Injectable>(&mut self) -> &mut Self {
        self.interceptors.push(EnhancerRef::interceptor::<I>());
        self
    }

    /// An exception filter for every route of this controller, tried before global filters.
    pub fn filter<F: ExceptionFilter + Injectable>(&mut self) -> &mut Self {
        self.filters.push(EnhancerRef::filter::<F>());
        self
    }

    /// Controller-level metadata, visible to every route unless a handler overrides the same type.
    pub fn meta<T: Send + Sync + 'static>(&mut self, value: T) -> &mut Self {
        self.meta.insert(value);
        self
    }

    /// Registers a handler. `handler` receives `Arc<Self>` followed by any axum extractors.
    pub fn route<H, Args>(
        &mut self,
        method: Method,
        path: impl Into<String>,
        name: &'static str,
        handler: H,
    ) -> &mut RouteDef
    where
        H: RouteHandler<C, Args>,
    {
        let filter = MethodFilter::try_from(method.clone()).ok();
        self.routes.push(RouteDef {
            method,
            path: path.into(),
            name,
            guards: Vec::new(),
            interceptors: Vec::new(),
            filters: Vec::new(),
            meta: Metadata::default(),
            method_supported: filter.is_some(),
            build: Box::new(move |handle: ErasedHandle| {
                let filter = filter.expect("unsupported methods are rejected by the bootstrap");
                handler.into_method_router(Handle::<C>::from_erased(handle), filter)
            }),
        });
        self.routes.last_mut().expect("route was just pushed")
    }

    /// Shorthand for [`route`](Self::route) with `GET`.
    pub fn get<H, Args>(
        &mut self,
        path: impl Into<String>,
        name: &'static str,
        handler: H,
    ) -> &mut RouteDef
    where
        H: RouteHandler<C, Args>,
    {
        self.route(Method::GET, path, name, handler)
    }

    /// Shorthand for [`route`](Self::route) with `POST`.
    pub fn post<H, Args>(
        &mut self,
        path: impl Into<String>,
        name: &'static str,
        handler: H,
    ) -> &mut RouteDef
    where
        H: RouteHandler<C, Args>,
    {
        self.route(Method::POST, path, name, handler)
    }

    /// Shorthand for [`route`](Self::route) with `PUT`.
    pub fn put<H, Args>(
        &mut self,
        path: impl Into<String>,
        name: &'static str,
        handler: H,
    ) -> &mut RouteDef
    where
        H: RouteHandler<C, Args>,
    {
        self.route(Method::PUT, path, name, handler)
    }

    /// Shorthand for [`route`](Self::route) with `PATCH`.
    pub fn patch<H, Args>(
        &mut self,
        path: impl Into<String>,
        name: &'static str,
        handler: H,
    ) -> &mut RouteDef
    where
        H: RouteHandler<C, Args>,
    {
        self.route(Method::PATCH, path, name, handler)
    }

    /// Shorthand for [`route`](Self::route) with `DELETE`.
    pub fn delete<H, Args>(
        &mut self,
        path: impl Into<String>,
        name: &'static str,
        handler: H,
    ) -> &mut RouteDef
    where
        H: RouteHandler<C, Args>,
    {
        self.route(Method::DELETE, path, name, handler)
    }
}

impl RouteDef {
    /// A guard for this route, run after global and controller guards.
    pub fn guard<G: Guard + Injectable>(&mut self) -> &mut Self {
        self.guards.push(EnhancerRef::guard::<G>());
        self
    }

    /// An interceptor around this route, the innermost.
    pub fn interceptor<I: Interceptor + Injectable>(&mut self) -> &mut Self {
        self.interceptors.push(EnhancerRef::interceptor::<I>());
        self
    }

    /// An exception filter for this route, tried before controller and global filters.
    pub fn filter<F: ExceptionFilter + Injectable>(&mut self) -> &mut Self {
        self.filters.push(EnhancerRef::filter::<F>());
        self
    }

    /// Metadata for this route; takes precedence over a controller-level value of the same type.
    pub fn meta<T: Send + Sync + 'static>(&mut self, value: T) -> &mut Self {
        self.meta.insert(value);
        self
    }
}
