//! Core of the hornero framework: a NestJS-style module system and DI container on top of axum.
//!
//! Most applications depend on the `hornero` facade crate, which re-exports this crate together with
//! the procedural macros and axum itself.

#![warn(missing_docs)]

mod app;
mod di;
mod error;
mod lifecycle;
mod util;
mod web;

pub use app::{App, Hornero};
pub use di::dependency::{Dependency, Qualified};
pub use di::injectable::{Injectable, LifecycleFn, Scope, hooks};
pub use di::key::Key;
pub use di::module::{Identity, Module, ModuleDef, ModuleKey, Provide};
pub use di::provider::{FactoryFn, ProviderDef};
pub use di::resolver::Resolver;
pub use error::{BootError, HttpError, Problem, ShutdownError};
pub use lifecycle::{Hook, Lifecycle, Shutdown};
pub use util::{BoxError, BoxFuture};
pub use web::chain::ErrorRenderer;
pub use web::controller::{Controller, ControllerAttrs, ControllerDef, RouteDef};
pub use web::enhancer::{AppFilter, AppGuard, AppInterceptor};
pub use web::extractor::{Extracted, Extractor};
pub use web::filter::ExceptionFilter;
pub use web::guard::{Guard, GuardContext};
pub use web::handler::RouteHandler;
pub use web::interceptor::{CallHandler, Interceptor};
pub use web::middleware::Middleware;
pub use web::route::{Metadata, RouteContext};
pub use web::routes::{EnhancerInfo, RouteInfo, Routes};

/// Items used by code generated by `hornero-macros`. Not part of the public API.
#[doc(hidden)]
pub mod __private {
    pub use crate::lifecycle::ErasedLifecycle;
    pub use axum::http::Method;
}
